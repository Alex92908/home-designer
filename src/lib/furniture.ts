// Helper: get furniture by ID
// Custom furniture registry (populated at runtime by store)
const _customItems: FurnitureItem[] = [];
export function registerFurniture(item: FurnitureItem): void {
  const idx = _customItems.findIndex(f => f.id === item.id);
  if (idx >= 0) _customItems[idx] = item; else _customItems.push(item);
}

export function getFurnitureById(id: string): FurnitureItem | undefined {
  return FURNITURE.find(f => f.id === id) ?? _customItems.find(f => f.id === id);
}

export function getCustomFurniture(): FurnitureItem[] { return _customItems; }

// Helper: get furniture for a room
export function getFurnitureForRoom(room: import("./types").RoomType): FurnitureItem[] {
  return FURNITURE.filter(f => f.roomTypes.includes(room));
}

