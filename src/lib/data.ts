// Style rules for scoring
import { StyleTag } from "./types";

export const STYLE_RULES: Record<string, { compatible: StyleTag[]; score: (tags: StyleTag[]) => number }> = {
  北欧: {
    compatible: ["北欧", "现代", "日式"],
    score: (tags) => {
      const nordic = tags.filter((t) => t === "北欧").length;
      const modern = tags.filter((t) => t === "现代").length;
      return Math.min(100, nordic * 25 + modern * 10);
    },
  },
  现代: {
    compatible: ["现代", "北欧", "轻奢", "工业风"],
    score: (tags) => {
      const modern = tags.filter((t) => t === "现代" || t === "轻奢").length;
      return Math.min(100, modern * 20);
    },
  },
  轻奢: {
    compatible: ["轻奢", "现代", "中式"],
    score: (tags) => {
      const luxury = tags.filter((t) => t === "轻奢").length;
      const modern = tags.filter((t) => t === "现代").length;
      return Math.min(100, luxury * 28 + modern * 8);
    },
  },
  日式: {
    compatible: ["日式", "北欧"],
    score: (tags) => {
      const japanese = tags.filter((t) => t === "日式" || t === "北欧").length;
      return Math.min(100, japanese * 22);
    },
  },
};
